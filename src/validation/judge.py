import json
import logging
import os
import torch
import re
from tqdm import tqdm
from transformers import AutoModelForCausalLM, AutoTokenizer
from peft import PeftModel
from settings import Settings
from utils.file_utils import dataset_root, output_root
from utils.torch_utils import get_device
from openai import OpenAI

JUDGE_MODEL = "gpt-4o-mini"

JUDGE_PROMPT = """
You are a financial expert and AI model auditor.
Evaluate the relevance of the response generated by a model by comparing it to the user's question and the reference answer.

Evaluation criteria:
1. Financial rigor (calculations, economic principles, absence of fabricated figures/hallucinations).
2. Clarity of reasoning (logical and justifiable chain of thought).
3. Relevance and completeness regarding the user's need.

Assign a strict score from 1 to 5:
1 = Dangerous, false, or off-topic.
2 = Notable financial errors or inconsistent reasoning.
3 = Partially correct, but incomplete or contains imprecise calculations.
4 = Sound reasoning, financially accurate, clear formulation.
5 = Excellent, precise, rigorous, and comprehensive.

Respond STRICTLY in this format:
Score: <score from 1 to 5>
Justification: <brief explanation>
"""

def score_with_llm(settings: Settings):

    logging.info(f"\n--- Scoring model with LLM as judge ---")

    if os.getenv("OPENAI_API_KEY") is None:
        logging.warning("no OPENAI_API_KEY configured in env; skipping")
        return

    client = OpenAI()  # need OPENAI_API_KEY in environment

    device = get_device()

    path_to_adapter = f"{output_root()}/adapter"

    tokenizer = AutoTokenizer.from_pretrained(settings.model_name, trust_remote_code=True)

    base_model = AutoModelForCausalLM.from_pretrained(
        settings.model_name,
        torch_dtype=torch.bfloat16,
        device_map=device,
        trust_remote_code=True,
    )

    model = PeftModel.from_pretrained(base_model, path_to_adapter)
    model.eval()

    path_to_dataset_eval = f"{dataset_root()}/{settings.validation_set}"

    with open(path_to_dataset_eval, "r", encoding="utf-8") as f:
        records = [json.loads(line) for line in f]
        sample_size = len(records)

    scores = []

    for row in tqdm(records):
        logging.info(f"Evaluating {row}")

        messages = row['messages']
        for message in messages:
            if (message['role'] == 'user'):
                reference_question = message['content']
            if (message['role'] == 'assistant'):
                reference_answer = message['content']

        tokenized_input = tokenizer(reference_question, return_tensors="pt").to(device)

        with torch.no_grad():
            trained_model_output = model.generate(
                **tokenized_input,
                max_new_tokens=2048,
                temperature=0.2,
                do_sample=True,
                eos_token_id=tokenizer.eos_token_id,
            )

        trained_model_answer = tokenizer.decode(
            trained_model_output[0][tokenized_input.input_ids.shape[1]:], skip_special_tokens=True
        )

        judge_input = f"""
### Question from user :
```
{reference_question}
```

### Reference answer :
```
{reference_answer}
```

### Answer from trained model you are evaluating :
```
{trained_model_answer}
```
"""

        completion = client.chat.completions.create(
            model=JUDGE_MODEL,
            messages=[
                {"role": "system", "content": JUDGE_PROMPT},
                {"role": "user", "content": judge_input},
            ],
            temperature=0.0,
        )

        verdict = completion.choices[0].message.content

        logging.info(f"Judgement {verdict}")

        match = re.search(r"Score:\s*(\d+)", verdict)
        if match:
            score = int(match.group(1))
            scores.append(score)

    avg_score = sum(scores) / len(scores) if scores else 0
    logging.info(f"\n--- Results ---")
    logging.info(f"Number of scored samples : {len(scores)}/{sample_size}")
    logging.info(f"Average score : {avg_score:.2f} / 5")
